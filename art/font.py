# 3x5 pixel font (caps) for painted signs
F={
'A':'010101111101101','B':'110101110101110','C':'011100100100011','D':'110101101101110','E':'111100110100111',
'F':'111100110100100','G':'011100101101011','H':'101101111101101','I':'111010010010111','K':'101101110101101',
'L':'100100100100111','N':'110101101101101','O':'010101101101010','P':'110101110100100','R':'110101110101101',
'S':'011100010001110','T':'111010010010010','U':'101101101101111','Y':'101101010010010','$':'011110010011110',
'W':'101101101111101','M':'101111111101101','V':'101101101101010',' ':'000000000000000','.':'000000000000010',
}
def text(c,x,y,s,col,sh=None):
    for i,ch in enumerate(s):
        g=F[ch]
        for r in range(5):
            for q in range(3):
                if g[r*3+q]=='1':
                    if sh: c.px(x+i*4+q+1,y+r+1,sh)
                    c.px(x+i*4+q,y+r,col)
def width(s): return len(s)*4-1
